interface IconPaths {
  ink: string;
  tone: string;
}

// Merges horizontal runs of each tone into one rect subpath, so every icon is
// two paths regardless of how many cells it has.
function toPaths(rows: readonly string[]): IconPaths {
  const paths: IconPaths = { ink: '', tone: '' };

  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const cell = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === cell) end += 1;
      const rect = `M${x} ${y}h${end - x}v1h${x - end}z`;
      if (cell === '#') paths.ink += rect;
      else if (cell === '+') paths.tone += rect;
      x = end;
    }
  });

  return paths;
}

const TOOL_PATHS: Record<string, IconPaths> = Object.fromEntries(
  Object.entries(TOOL_BITMAPS).map(([tool, rows]) => [tool, toPaths(rows)]),
);

export function ToolIcon({ tool }: { tool: string }) {
  const { ink, tone } = TOOL_PATHS[tool] ?? TOOL_PATHS.brush;

  return (
    <svg
      width={ICON_SIZE}
      height={ICON_SIZE}
      viewBox={`0 0 ${ICON_SIZE} ${ICON_SIZE}`}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      {tone && <path d={tone} opacity={TONE_OPACITY} />}
      <path d={ink} />
    </svg>
  );
}
